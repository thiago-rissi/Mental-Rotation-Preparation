// Command mental-rotation-preparation (experiment Mental-Rotation-Preparation)
// runs a reduced replication of Cooper & Shepard (1973),
// "The time required to prepare for a rotated stimulus", Memory & Cognition
// 1(3), 246-250.
//
// A single rotated character is shown; the participant says whether it is
// normal or backward (mirror-reversed), whatever its orientation. Blocked
// conditions vary the advance information: none (N), or an outline of the
// upright normal character followed by an arrow showing where the top of the
// character will be, for 400 or 1000 ms (B400, B1000). Condition C (outline
// already rotated) and B100/B700 are implemented and can be added back in
// DefaultConfig.
//
// Usage:
//
//	mental-rotation-preparation                    a participant (random number, fullscreen, English)
//	mental-rotation-preparation -s 7               participant number 7 instead of a random one
//	mental-rotation-preparation -w -lang fr        windowed, French
//	mental-rotation-preparation -s 1 -w -quick     3 short blocks, for debugging
//	mental-rotation-preparation -w -sheet          stimulus check sheet (arrows change orientation)
//
// In the browser the same flags are URL parameters: ?s=7, ?s=1&quick.
//
// Data go to ./data unless GOXPY_DATA is set (desktop), or to one .zip
// download at the end of the session (browser).
package main

