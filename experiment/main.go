//go:embed assets/Inconsolata.ttf
var fontData []byte

const expName = "Mental-Rotation-Preparation"

// defaultDataDir is used when GOXPY_DATA is not set (relative to the current
// directory).
const defaultDataDir = "data"

var dataColumns = []string{
	"practice", "block_index", "trial_in_block", "trial_global", "condition",
	"cue_ms_planned", "cue_frames", "character", "version", "orientation_deg",
	"angular_departure", "key_mapping", "response_key", "response", "correct",
	"timeout", "rt_ms", "test_onset_ns", "key_ts_ns", "identity_onset_ns",
	"arrow_onset_ns", "blank_onset_ns", "arrow_ms_measured", "frame_ms", "seed",
}

func main() {
	quick := flag.Bool("quick", false, "debugging: 3 blocks (one per condition) of 6 trials")
	lang := flag.String("lang", "en", "language of the on-screen text: en or fr")
	sheet := flag.Bool("sheet", false, "show the stimulus check sheet instead of running the experiment")
	auto := flag.Bool("autopilot", false,
		"TESTING ONLY: the program presses the keys itself (random responses); never use with a participant")

	// The results directory is fixed when the experiment is initialised, so the
	// ./data default has to be in place before NewExperimentFromFlags (an
	// exp.SetOutputDirectory afterwards would come too late).
	if strings.TrimSpace(os.Getenv("GOXPY_DATA")) == "" {
		if err := os.Setenv("GOXPY_DATA", defaultDataDir); err != nil {
			log.Fatalf("setting GOXPY_DATA: %v", err)
		}
	}

	// No -s: draw the participant number at random instead of letting
	// goxpyriment open its setup dialog (see subject.go). In the browser the
	// flags come from the page address, where webapp/index.html has already put
	// a random number.
	randomID := false
	if runtime.GOOS != "js" {
		os.Args, randomID = withSubject(os.Args, randomSubject())
	}

	exp := control.NewExperimentFromFlags(expName, bgColor, fgColor, 28)
	defer exp.End()
	if randomID {
		exp.AddExperimentInfo("subject id: drawn at random by the program (no -s given)")
	}

	tx, err := TextsFor(*lang)
	if err != nil {
		exp.Fatal("-lang: %v", err)
	}
	cfg := DefaultConfig()
	if err := cfg.Validate(); err != nil {
		exp.Fatal("%v", err)
	}

	var ap *autopilot
	if *auto {
		ap = newAutopilot()
		exp.AddExperimentInfo("AUTOPILOT: responses were generated by the program, not by a person")
		log.Printf("AUTOPILOT: responses are generated by the program")
	}

	if *sheet {
		runOrDie(exp, func() error { return runSheet(exp, cfg, ap) })
		return
	}

	subject, ok := exp.Subject.Number()
	if !ok || subject < 1 {
		exp.Fatal("the subject ID must be a positive integer (e.g. -s 7), or left out to draw one at random; "+
			"got %q: it selects the condition order and the response keys", exp.Subject.String())
	}
	session, err := BuildSession(cfg, subject, *quick)
	if err != nil {
		exp.Fatal("building the trial list: %v", err)
	}
	mapping := MappingFor(subject)

	exp.AddDataVariableNames(dataColumns)
	exp.AddExperimentInfo(fmt.Sprintf("seed: %d", session.Seed))
	exp.AddExperimentInfo("key_mapping: " + mapping.String())
	exp.AddExperimentInfo("condition order (Latin-square row): " + strings.Join(session.Order, ","))
	exp.AddExperimentInfo("block order: " + session.BlockOrder())
	exp.AddExperimentInfo(fmt.Sprintf("quick: %v, lang: %s", *quick, tx.Lang))
	exp.AddExperimentInfo(fmt.Sprintf("config: %+v", cfg))

	r := &runner{exp: exp, cfg: cfg, tx: tx, mapping: mapping, session: session, auto: ap}
	runOrDie(exp, r.run)
}

// runOrDie runs body once inside exp.Run (where all SDL work must happen).
func runOrDie(exp *control.Experiment, body func() error) {
	err := exp.Run(func() error {
		if err := body(); err != nil {
			return err
		}
		return control.EndLoop
	})
	if err != nil && !control.IsEndLoop(err) {
		exp.Fatal("experiment error: %v", err)
	}
}

// textSizeRatio is the default font size relative to the height of the drawing
// area: 28 pt on the browser's 1024x768 canvas.
const textSizeRatio = 28.0 / 768

// setupDisplay sets the text size, reads the frame duration and pre-renders
// the stimuli. Everything is sized relative to exp.DrawArea().
func setupDisplay(exp *control.Experiment, cfg Config) (*Stimuli, time.Duration, error) {
	_, h := exp.DrawArea()
	size := float32(math.Round(float64(h * textSizeRatio)))
	old := exp.DefaultFont
	if err := exp.LoadFontFromMemory(fontData, size); err != nil {
		return nil, 0, fmt.Errorf("loading the text font: %w", err)
	}
	if old != nil {
		old.Close()
	}
	exp.DefaultFontSize = size // also the ceiling of the instruction screens

	nominal := exp.Screen.FrameDuration()
	measured, err := measureFrame(exp, 120)
	if err != nil {
		return nil, 0, fmt.Errorf("measuring the refresh rate: %w", err)
	}
	// Durations are counted in frames of this length. On the desktop the
	// display mode gives the exact rate; in a browser the "display mode" is a
	// fiction and frames are paced by requestAnimationFrame, so the measured
	// period is the only real one.
	frame, source := nominal, "nominal"
	if runtime.GOOS == "js" || nominal <= 0 {
		frame, source = measured, "measured"
	}
	if frame <= 0 {
		return nil, 0, fmt.Errorf("could not determine the frame duration")
	}
	msg := fmt.Sprintf("frame duration: nominal %.4f ms, measured %.4f ms; using the %s %.4f ms (%.3f Hz)",
		ms(nominal), ms(measured), source, ms(frame), 1e9/float64(frame))
	if nominal > 0 {
		if d := math.Abs(float64(measured-nominal)) / float64(nominal); d > 0.05 {
			log.Printf("WARNING: measured frame %.3f ms differs from nominal %.3f ms by %.0f%% "+
				"(unfocused window? dropped frames?)", ms(measured), ms(nominal), 100*d)
			msg += " (WARNING: nominal and measured differ by more than 5%)"
		}
	}
	log.Print(msg)
	exp.AddExperimentInfo(msg)

	st, err := NewStimuli(exp.Screen, fontData, cfg.Characters, h)
	if err != nil {
		return nil, 0, fmt.Errorf("rendering the stimuli: %w", err)
	}
	info := fmt.Sprintf("stimuli: draw area height %.0f px, text %.0f pt, glyph ink height %.0f px (font %.1f pt), "+
		"aperture diameter %.0f px, outline band +-%d px; outline hollow: %v (interior covered %.2f over >= %d px)",
		h, size, st.GlyphH, st.FontPt, 2*st.ApR, st.OutlinePx, st.CueHollow, st.HollowScore, st.HollowN)
	log.Print(info)
	exp.AddExperimentInfo(info)
	if !st.CueHollow {
		log.Printf("WARNING: the outline did not come out hollow; the cues are grey filled glyphs instead")
	}
	return st, frame, nil
}

// measureFrame flips n blank frames and estimates the frame period from their
// timestamps (see framePeriod).
func measureFrame(exp *control.Experiment, n int) (time.Duration, error) {
	ts := make([]uint64, n)
	for i := range ts {
		if err := exp.Screen.Clear(); err != nil {
			return 0, err
		}
		t, err := exp.Screen.FlipTS()
		if err != nil {
			return 0, err
		}
		ts[i] = t
	}
	return framePeriod(ts)
}

func ms(d time.Duration) float64 { return float64(d) / float64(time.Millisecond) }

// runner runs the experiment proper.
type runner struct {
	exp     *control.Experiment
	cfg     Config
	tx      Texts
	mapping KeyMapping
	session Session
	auto    *autopilot

	st      *Stimuli
	frame   time.Duration
	errMsg  *stimuli.TextLine
	slowMsg *stimuli.TextLine
}

var responseKeys = []control.Keycode{control.K_F, control.K_J}

func (r *runner) frames(ms int) int { return Frames(ms, r.frame) }

func (r *runner) run() error {
	st, frame, err := setupDisplay(r.exp, r.cfg)
	if err != nil {
		return err
	}
	defer st.Destroy()
	r.st, r.frame = st, frame

	est := EstimateTrials(r.cfg, r.session, frame, 700*time.Millisecond, 0.1)
	log.Printf("%d main trials in %d blocks; block order %s; trials alone should take about %.1f min",
		r.session.NumMainTrials(), len(r.session.Blocks), r.session.BlockOrder(), est.Minutes())

	// Feedback is centred below the circle, which stays on screen.
	_, h := r.exp.DrawArea()
	fbY := -(st.ApR + 0.05*h)
	r.errMsg = stimuli.NewTextLine(r.tx.Error, 0, fbY, feedbackColor)
	r.slowMsg = stimuli.NewTextLine(r.tx.TooSlow, 0, fbY, feedbackColor)
	defer r.errMsg.Unload()
	defer r.slowMsg.Unload()

	// Instructions, then practice.
	for _, text := range []string{
		r.tx.Welcome(r.mapping),
		r.tx.BlockTypes,
		r.tx.Practice(len(r.session.Practice)),
	} {
		if err := r.waitSpace(text); err != nil {
			return err
		}
	}
	if err := r.runTrials(r.session.Practice); err != nil {
		return err
	}
	nBlocks := len(r.session.Blocks)
	if err := r.waitSpace(r.tx.AfterPractice(nBlocks, len(r.session.Blocks[0].Trials))); err != nil {
		return err
	}

	// Main blocks, each introduced by a self-paced screen that doubles as the
	// break.
	for _, b := range r.session.Blocks {
		def := conditionCatalog[b.Condition]
		runtime.GC() // collect now, while the participant reads, not during a trial
		text := r.tx.BlockIntro(def, b.Index, nBlocks, r.mapping)
		if b.Index > 1 {
			text = r.tx.BlockDone(b.Index-1) + "\n\n" + text
		}
		if err := r.waitSpace(text); err != nil {
			return err
		}
		if err := r.runTrials(b.Trials); err != nil {
			return err
		}
		if err := r.exp.Data.Save(); err != nil {
			return fmt.Errorf("saving data: %w", err)
		}
	}

	if err := r.debrief(); err != nil {
		return err
	}
	return r.showEnd()
}

// showEnd shows the closing screen and waits for any key.
//
// Desktop: the screen gives the full path of the CSV, which is already on disk
// (it is saved after every block).
//
// Browser: the data only leave the page as the single .zip download that
// DataFile.Finalize makes, which Experiment.End would trigger only after this
// screen. A participant who closed the tab here instead of pressing a key would
// lose the session, and the screen would say "has downloaded" before anything
// had. So the data are finalized first, then the screen is shown; exp.Data is
// cleared afterwards, so that End does not finalize (and download) a second
// time.
func (r *runner) showEnd() error {
	var text string
	if runtime.GOOS == "js" {
		r.exp.Data.WriteEndTime()
		if err := r.exp.Data.Finalize(); err != nil {
			return fmt.Errorf("saving the data: %w", err)
		}
		log.Printf("Results downloaded as %s", strings.TrimSuffix(r.exp.Data.Filename, ".csv")+".zip")
		r.exp.Data = nil
		text = r.tx.EndBrowser
	} else {
		path, err := filepath.Abs(r.exp.Data.FullPath)
		if err != nil {
			path = r.exp.Data.FullPath
		}
		// Folder and file name on separate lines, so that the wrapping of a long
		// path never splits the file name.
		text = r.tx.End(filepath.Dir(path) + string(filepath.Separator) + "\n" + filepath.Base(path))
	}
	rt, err := newRichText(r.exp, text)
	if err != nil {
		return err
	}
	defer rt.Unload()
	if r.auto != nil {
		r.auto.snapshot(r.exp, "end")
		r.auto.pressAfter(control.K_SPACE, 300*time.Millisecond)
	}
	if err := r.exp.Show(stimuli.DrawFunc(rt.Draw)); err != nil {
		return err
	}
	r.exp.Keyboard.Clear()
	_, err = r.exp.Keyboard.Wait()
	return err
}

// waitSpace shows a text screen until SPACE. The text may contain bold and
// boxed parts (see richtext.go).
func (r *runner) waitSpace(text string) error {
	rt, err := newRichText(r.exp, text)
	if err != nil {
		return err
	}
	defer rt.Unload()
	if r.auto != nil {
		r.auto.snapshot(r.exp, "text")
		r.auto.pressAfter(control.K_SPACE, 300*time.Millisecond)
	}
	if err := r.exp.Show(stimuli.DrawFunc(rt.Draw)); err != nil {
		return err
	}
	return r.exp.Keyboard.WaitKey(control.K_SPACE)
}

// snap takes a screenshot of the next frame in autopilot mode, for the first
// trial of each block only.
func (r *runner) snap(t Trial, what string) {
	if r.auto != nil && t.TrialInBlock == 1 {
		r.auto.snapshot(r.exp, fmt.Sprintf("%s_%s_%s%d_%s", t.Condition, what, t.Character, t.Orientation, t.Version))
	}
}

// runTrials runs a list of trials with the garbage collector off.
func (r *runner) runTrials(trials []Trial) error {
	old := debug.SetGCPercent(-1)
	defer debug.SetGCPercent(old)
	for _, t := range trials {
		if err := r.runTrial(t); err != nil {
			if control.IsEndLoop(err) {
				log.Printf("Session interrupted (ESC or window closed) during %s trial %d of block %d",
					t.Condition, t.TrialInBlock, t.Block)
				r.exp.AddExperimentInfo(fmt.Sprintf("INTERRUPTED (ESC or window closed) at block %d, trial %d",
					t.Block, t.TrialInBlock))
			}
			return err
		}
	}
	return nil
}

// drainEvents empties the event queue right before the test display, so that
// a key pressed during the cue cannot be taken as the response. ESC and window
// close still end the session.
func drainEvents() error {
	var ev control.Event
	for control.PollEvent(&ev) {
		switch ev.Type {
		case control.EVENT_QUIT:
			return control.EndLoop
		case control.EVENT_KEY_DOWN:
			if ev.KeyboardEvent().Key == control.K_ESCAPE {
				return control.EndLoop
			}
		}
	}
	return nil
}

// opt returns "" for a timestamp that was not taken, so the CSV field is empty.
func opt(ns uint64) any {
	if ns == 0 {
		return ""
	}
	return ns
}

func round3(x float64) float64 { return math.Round(x*1000) / 1000 }

// runTrial presents one trial and writes its data row. Every timed display is
// a whole number of frames (ShowFrames); the test appears on the flip right
// after the last frame of the preceding display.
func (r *runner) runTrial(t Trial) error {
	exp, st, tm := r.exp, r.st, r.cfg.Timing
	def := conditionCatalog[t.Condition]

	var identOn, arrowOn, blankOn uint64
	var cueMs, cueFrames any = "", ""
	var err error
	switch def.Kind {
	case KindN:
		r.snap(t, "1blank")
		blankOn, err = exp.ShowFrames(st.ApertureScene(), r.frames(tm.WarningMs))
	case KindB:
		r.snap(t, "1identity")
		identOn, err = exp.ShowFrames(st.CueScene(t.Character, 0), r.frames(tm.IdentityMs))
		if err == nil {
			n := r.frames(def.ArrowMs)
			cueMs, cueFrames = def.ArrowMs, n
			r.snap(t, "2arrow")
			arrowOn, err = exp.ShowFrames(st.ArrowScene(t.Orientation), n)
		}
	case KindC:
		r.snap(t, "1cue")
		identOn, err = exp.ShowFrames(st.CueScene(t.Character, t.Orientation), r.frames(tm.CombinedCueMs))
		if err == nil {
			blankOn, err = exp.ShowFrames(st.ApertureScene(), r.frames(tm.CombinedBlankMs))
		}
	}
	if err != nil {
		return fmt.Errorf("cue display: %w", err)
	}
	if err := drainEvents(); err != nil {
		return err
	}

	// Test: one flip, then it stays on screen while we wait for the key.
	r.snap(t, "3test")
	testOn, err := exp.ShowFrames(st.TestScene(t), 1)
	if err != nil {
		return fmt.Errorf("test display: %w", err)
	}
	if r.auto != nil {
		r.auto.respond(t, r.mapping)
	}
	remaining := tm.TimeoutMs - int((control.TicksNS()-testOn)/uint64(time.Millisecond))
	key, keyTS, err := exp.Keyboard.GetKeyEventTS(responseKeys, max(remaining, 1))
	if err != nil {
		return err
	}

	keyName := ""
	switch key {
	case control.K_F:
		keyName = "f"
	case control.K_J:
		keyName = "j"
	}
	timeout := key == 0
	response := r.mapping.Response(keyName)
	correct := !timeout && response == t.Version
	var rt, keyTSv any = "", ""
	if !timeout {
		rt = round3(float64(int64(keyTS)-int64(testOn)) / 1e6)
		keyTSv = keyTS
	}
	var arrowMeasured any = ""
	if arrowOn != 0 {
		arrowMeasured = round3(float64(testOn-arrowOn) / 1e6)
	}

	// Feedback (errors and timeouts only), then the inter-trial interval.
	if r.auto != nil && (timeout || !correct) {
		r.auto.snapshotOnce(exp, fmt.Sprintf("feedback_timeout%v", timeout))
	}
	switch {
	case timeout:
		_, err = exp.ShowFrames(st.MessageScene(r.slowMsg), r.frames(tm.FeedbackMs))
	case !correct:
		_, err = exp.ShowFrames(st.MessageScene(r.errMsg), r.frames(tm.FeedbackMs))
	}
	if err != nil {
		return fmt.Errorf("feedback: %w", err)
	}
	if _, err := exp.ShowFrames(st.ApertureScene(), r.frames(tm.ITIMs)); err != nil {
		return fmt.Errorf("inter-trial interval: %w", err)
	}

	practice := 0
	if t.Practice {
		practice = 1
	}
	exp.Data.Add(
		practice, t.Block, t.TrialInBlock, t.Global, t.Condition,
		cueMs, cueFrames, t.Character, t.Version, t.Orientation,
		t.Departure, r.mapping.String(), keyName, response, b2i(correct),
		b2i(timeout), rt, testOn, keyTSv, opt(identOn),
		opt(arrowOn), opt(blankOn), arrowMeasured, round3(ms(r.frame)), r.session.Seed,
	)
	return nil
}

func b2i(b bool) int {
	if b {
		return 1
	}
	return 0
}

// debrief asks the end-of-session question. The answer goes into the
// -info.txt (so it travels with the data, including inside the browser's .zip)
// and, on the desktop, also into its own file next to the data file.
func (r *runner) debrief() error {
	answer, err := r.askText(r.tx.DebriefPrompt, r.tx.DebriefHint)
	// Save whatever was typed, even if the session was then quit with ESC.
	r.exp.AddExperimentInfo("debrief question: " + r.tx.DebriefPrompt)
	r.exp.AddExperimentInfo(fmt.Sprintf("debrief answer: %q", answer))
	if runtime.GOOS == "js" {
		return err // no filesystem in the browser
	}
	path := strings.TrimSuffix(r.exp.Data.FullPath, filepath.Ext(r.exp.Data.FullPath)) + "_debrief.txt"
	content := fmt.Sprintf("subject_id: %s\nlang: %s\nquestion: %s\nanswer: %s\n",
		r.exp.Subject.String(), r.tx.Lang, strings.ReplaceAll(r.tx.DebriefPrompt, "\n", " "), answer)
	if werr := os.WriteFile(path, []byte(content), 0o644); werr != nil {
		return fmt.Errorf("saving the debrief answer: %w", werr)
	}
	log.Printf("Debrief answer saved in %s", path)
	return err
}
